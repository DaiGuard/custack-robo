namespace Custack.Equipment
{
    /// <summary>
    /// アームユニットのデバイスID定義
    /// 0x01: ガトリング (連射・短射程・弾幕)
    /// 0x02: ソード (近接・高威力・薙ぎ払い)
    /// 0x03: 大型レーザーキャノン (極大威力・長射程・ビーム)
    /// </summary>
    public enum ArmDeviceType : byte
    {
        None = 0x00,
        Gatling = 0x01,  // 0x01: ガトリング (連射・短射程・黄色弾幕)
        Sword = 0x02,    // 0x02: ソード (近接高威力・斬撃波 / 薙ぎ払い)
        Cannon = 0x03    // 0x03: 大型レーザーキャノン (極大威力・貫通長射程レーザー)
    }

    /// <summary>
    /// 脚ユニットのデバイスID定義
    /// 0x01: オムニホイール (4輪X配置: 全方向スライド、悪路減速大)
    /// 0x02: 二輪差動 (前後最高速・旋回鋭い、泥でスタック)
    /// 0x03: キャタピラ (超信地旋回、悪路走破性最強・溶岩軽減)
    /// </summary>
    public enum LegDeviceType : byte
    {
        None = 0x00,
        Omni = 0x01,     // 0x01: オムニホイール (全方向スライド)
        Tire = 0x02,     // 0x02: 二輪差動 (前後高速)
        Crawler = 0x03   // 0x03: キャタピラ (悪路走破)
    }
}
